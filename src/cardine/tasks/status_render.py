"""Deterministic generated queue and plan status region, written only on request."""
from __future__ import annotations

import hashlib
import os
import re
import tempfile
from pathlib import Path

from cardine.shared.errors import CardineError
from cardine.tasks.state import STATUSES
from cardine.tasks.status import load_task_snapshot

REGION_BEGIN = "<!-- cardine-status:begin -->"
REGION_END = "<!-- cardine-status:end -->"
COMMAND = "cardine status --write"
DEFAULT_QUEUE = "tasks/QUEUE.md"
DEFAULT_PLAN = "PROJECT_PLAN.md"
PLAN_STUB = "# Project Plan\n\nHuman narrative and proposals live outside the generated region.\n\n"


def _cell(value: object) -> str:
    return re.sub(r"\s+", " ", str(value)).replace("|", "\\|").strip()


def _view_paths(root: Path, config: dict) -> tuple[Path, Path]:
    locations = config.get("locations", {})
    paths = []
    for relative in (locations.get("queue", DEFAULT_QUEUE), locations.get("plan", DEFAULT_PLAN)):
        path = (root / relative).resolve()
        if root != path and root not in path.parents:
            raise CardineError(f"view path escapes the project: {relative}")
        paths.append(path)
    return paths[0], paths[1]


def input_digest(root: Path, inputs: dict[Path, bytes], excluded: set[Path]) -> str:
    """Digest of the snapshot inputs, never of the generated views or of any clock."""
    digest = hashlib.sha256()
    for path in sorted(inputs):
        if path.resolve() in excluded:
            continue
        digest.update(path.relative_to(root).as_posix().encode() + b"\0")
        digest.update(hashlib.sha256(inputs[path]).digest())
    return digest.hexdigest()


def _header(digest: str) -> list[str]:
    return [f"<!-- Generated by `{COMMAND}`; input digest {digest}. Do not edit: rerun the command. -->"]


def _totals(model: dict) -> str:
    return "Totals: " + ", ".join(f"{key}={model['totals'][key]}" for key in (*STATUSES, "total"))


def render_queue(model: dict, digest: str) -> str:
    """Open tasks only; totals still count every validated task."""
    lines = ["# Task Execution Queue", "", *_header(digest), "", f"Preset: {model['preset']}", _totals(model), "",
             "| Status | ID | Title | Depends on | Blocked by | Startable | File |",
             "|--------|----|-------|------------|------------|-----------|------|"]
    for row in model["tasks"]:
        if row["status"] in ("done", "cancelled"):
            continue
        record = f"[{Path(row['record']).name}]({row['record']})" if row["record"] else "-"
        lines.append(f"| {row['status']} | {_cell(row['id'])} | {_cell(row['title'])} | {_cell(', '.join(row['dependencies']) or '-')} "
                     f"| {_cell(', '.join(row['blocked_by']) or '-')} | {str(row['startable']).lower()} | {record} |")
    return "\n".join(lines) + "\n"


def render_plan_region(model: dict, digest: str) -> str:
    """Every task, terminal ones included, between the region markers."""
    lines = [REGION_BEGIN, *_header(digest), "", f"Preset: {model['preset']}", _totals(model), "",
             "| Status | ID | Title | Phase |", "|--------|----|-------|-------|"]
    lines.extend(f"| {row['status']} | {_cell(row['id'])} | {_cell(row['title'])} | {_cell(row['phase'] or '-')} |" for row in model["tasks"])
    lines.append(REGION_END)
    return "\n".join(lines) + "\n"


def splice_region(plan: bytes | None, region: str) -> bytes:
    """Replace the single generated region, preserving every other byte of the plan."""
    block = region.rstrip("\n").encode()
    if plan is None:
        return PLAN_STUB.encode() + block + b"\n"
    if not plan.strip():
        return block + b"\n"
    begin, end = REGION_BEGIN.encode(), REGION_END.encode()
    if plan.count(begin) != 1 or plan.count(end) != 1 or plan.index(begin) > plan.index(end):
        raise CardineError(f"plan has a missing or malformed generated region; expected exactly one {REGION_BEGIN} before one {REGION_END}")
    start = plan.index(begin)
    stop = plan.index(end) + len(end)
    return plan[:start] + block + plan[stop:]


def _read(path: Path) -> bytes | None:
    try:
        return path.read_bytes()
    except FileNotFoundError:
        return None


def _replace(source: str, target: Path) -> None:
    os.replace(source, target)


def _stage(path: Path, content: bytes) -> str:
    path.parent.mkdir(parents=True, exist_ok=True)
    descriptor, temporary = tempfile.mkstemp(prefix=f".{path.name}.", dir=path.parent)
    with os.fdopen(descriptor, "wb") as stream:
        stream.write(content)
    return temporary


def _render_views(project_root: Path) -> tuple[dict, Path, Path, bytes, bytes, bytes | None, bytes | None]:
    root = Path(project_root).resolve()
    model, inputs, config = load_task_snapshot(root, all_tasks=True)
    if model["preset"] is None or model["diagnostics"]:
        detail = "; ".join(f"{item['path']}: {item['error']}" for item in model["diagnostics"])
        raise CardineError(f"incomplete status snapshot, views not written: {detail}")
    queue, plan = _view_paths(root, config)
    digest = input_digest(root, inputs, {queue, plan})
    old_queue, old_plan = _read(queue), _read(plan)
    return (model, queue, plan, render_queue(model, digest).encode(),
            splice_region(old_plan, render_plan_region(model, digest)), old_queue, old_plan)


def stale_views(project_root: Path) -> list[Path]:
    """Read-only drift check: the views a `--write` would change."""
    _, queue, plan, new_queue, new_plan, old_queue, old_plan = _render_views(project_root)
    return [path for path, new, old in ((queue, new_queue, old_queue), (plan, new_plan, old_plan)) if new != old]


def write_views(project_root: Path) -> list[Path]:
    """Replace the queue and the plan region from one snapshot; both change or neither does."""
    _, queue, plan, new_queue, new_plan, old_queue, old_plan = _render_views(project_root)
    changed = [(path, new, old) for path, new, old in ((queue, new_queue, old_queue), (plan, new_plan, old_plan)) if new != old]
    staged: list[tuple[str, Path, bytes | None]] = []
    replaced: list[tuple[Path, bytes | None]] = []
    try:
        for path, new, old in changed:
            staged.append((_stage(path, new), path, old))
        for temporary, path, old in staged:
            _replace(temporary, path)
            replaced.append((path, old))
    except OSError as error:
        for path, old in reversed(replaced):
            if old is None:
                path.unlink(missing_ok=True)
            else:
                restore = _stage(path, old)
                os.replace(restore, path)
        raise CardineError(f"views not written; previous content restored: {error}") from error
    finally:
        for temporary, _, _ in staged:
            if os.path.exists(temporary):
                os.unlink(temporary)
    return [path for path, _, _ in changed]
